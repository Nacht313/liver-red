const icoCache={};
export const ICON_NAMES = Object.keys(ICO);
export function icon(k) {
  if (icoCache[k]) return icoCache[k];
  const [g, a, b] = ICO[k] || ICO.walk;
  const c = document.createElement('canvas'); c.width = c.height = 8;
  const x = c.getContext('2d');
  g.forEach((r, y) => [...r].forEach((ch, i) => {
    if (ch === '#') { x.fillStyle = a; x.fillRect(i, y, 1, 1); } else if (ch === 'o') { x.fillStyle = b || a; x.fillRect(i, y, 1, 1); }
  }));
  return (icoCache[k] = c.toDataURL());
}
